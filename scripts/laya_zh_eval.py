def hf_cache_bytes():
    total = 0
    for base in (os.path.expanduser("~/.cache/huggingface"),):
        for root, _, files in os.walk(base):
            for f in files:
                try:
                    total += os.path.getsize(os.path.join(root, f))
                except OSError:
                    pass
    return total

def main():
    dl_before = hf_cache_bytes()
    t_load0 = time.time()
    from laya import Router
    router = Router(preload=True)
    load_ms = int((time.time() - t_load0) * 1000)
    dl_after = hf_cache_bytes()

    rows = []
    correct = 0
    brier = 0.0
    ms_all = []
    for i, (state, q, exp) in enumerate(CASES, 1):
        t0 = time.time()
        try:
            res = router.predict(state, {"q": {"type": "noul", "instructions": q}}, model="multilingual")
            p = res["answers"]["q"]["noul"]
            err = None
        except Exception as e:
            p = None
            err = str(e)[:160]
        ms = int((time.time() - t0) * 1000)
        if err or p is None:
            print("%2d ERR %s" % (i, err))
            rows.append({"i": i, "exp": exp, "p": None, "ms": ms, "err": err, "state": state, "q": q})
            continue
        ms_all.append(ms)
        pred = 1 if p >= 0.5 else 0
        ok = (pred == exp)
        correct += int(ok)
        brier += (p - exp) ** 2
        print("%2d exp=%d p=%.3f %s %dms" % (i, exp, p, "OK " if ok else "BAD", ms))
        rows.append({"i": i, "exp": exp, "p": p, "ms": ms, "ok": ok, "state": state, "q": q})

    n = sum(1 for r in rows if r.get("p") is not None)
    ms_sorted = sorted(ms_all)
    p50 = ms_sorted[len(ms_sorted) // 2] if ms_sorted else None
    p95 = ms_sorted[min(len(ms_sorted) - 1, int(len(ms_sorted) * 0.95))] if ms_sorted else None
    peak_mem_mb = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss / 1024.0  # Linux ru_maxrss is KB
    model_dl_mb = (dl_after - dl_before) / 1e6

    brier_avg = (brier / n) if n else None
    print("")
    print("accuracy %d/%d  brier %s  p50 %sms  p95 %sms  load %dms  peak_mem %.1fMB  model_dl %.1fMB" % (
        correct, n, ("%.4f" % brier_avg) if brier_avg is not None else "NA",
        p50, p95, load_ms, peak_mem_mb, model_dl_mb))
    print("PASS" if (n and correct >= 18 and brier_avg is not None and brier_avg <= 0.10) else "FAIL (do not enable)")

    out = {
        "model": MODEL_ID,
        "commit": COMMIT,
        "at": time.strftime("%Y-%m-%dT%H:%M:%S"),
        "rows": rows,
        "accuracy": [correct, n],
        "brier": brier_avg,
        "p50_ms": p50,
        "p95_ms": p95,
        "load_ms": load_ms,
        "peak_mem_mb": peak_mem_mb,
        "model_download_mb": model_dl_mb,
    }
    with io.open("laya_zh_eval_result.json", "w", encoding="utf-8", newline="\n") as f:
        f.write(json.dumps(out, ensure_ascii=False, indent=1))

if __name__ == "__main__":
    main()
